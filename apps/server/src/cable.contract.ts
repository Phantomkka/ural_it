import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { CABLE_SOURCE, CABLE_TARGET, cableRouteValid, cableLength, visibleCablePaths } from '@netcity/shared';
import { CableService } from './progress/cable.js';
import type { ProgressStore } from './progress/store.js';
export async function cableContract(store: ProgressStore) {
    const route = [CABLE_SOURCE, { x: 11, z: 0 }, { x: 16, z: 0 }, CABLE_TARGET];
    assert.equal(cableRouteValid(route), true);
    assert.ok(Math.abs(cableLength(route) - 11.8) < 1e-9);
    assert.equal(cableRouteValid([CABLE_SOURCE, CABLE_TARGET]), false);
    assert.equal(cableRouteValid([{ x: 0, z: -10 }, { x: 0, z: 10 }]), false);
    assert.equal(cableRouteValid([{ x: NaN, z: 0 }]), false);
    const duplicate = { x: 16, z: 0, cablePath: JSON.stringify({ id: 'line', revision: 1, points: route }) };
    assert.equal(visibleCablePaths([duplicate, duplicate]).size, 1);
    const guest = await store.register(), service = new CableService(store);
    let p = { x: 0, z: 0 }, sessionId = 'owner';
    const command = (action: string, extra = {}) => service.command(guest.profileId, { action, requestId: randomUUID(), ...extra }, () => ({ ...p, sessionId, entryOpen: true }));
    assert.equal((await command('take')).result.ok, false);
    p = { ...CABLE_SOURCE };
    const take = { action: 'take', requestId: randomUUID() };
    await service.command(guest.profileId, take, () => ({ ...p, sessionId, entryOpen: true }));
    assert.equal((await service.command(guest.profileId, take, () => ({ ...p, sessionId, entryOpen: true }))).result.replayed, true);
    assert.equal((await command('anchor', { x: 18, z: 0 })).result.ok, false);
    p = { ...CABLE_TARGET };
    assert.equal((await command('terminate')).result.ok, false);
    p = { x: 11, z: 0 };
    await command('anchor');
    p = { x: 16, z: 0 };
    sessionId = 'other';
    assert.equal((await command('anchor')).result.ok, false);
    sessionId = 'owner';
    await command('anchor');
    await command('drop');
    p = { x: 0, z: 0 };
    assert.equal((await command('take')).result.ok, false);
    p = { x: 16, z: 0 };
    await command('take');
    assert.equal((await command('terminate')).result.ok, true);
    assert.equal((await command('test')).result.ok, true);
    assert.equal((await command('test')).result.ok, false);
    const data = await store.read(guest.profileId);
    assert.equal(data.credits, 0);
    assert.equal(data.xp, 0);
    assert.equal(data.cable?.stage, 'TESTED');
    assert.equal(data.inventory.toolkit, 1);
    assert.equal((await command('reset')).result.ok, false);
    p = { ...CABLE_SOURCE };
    assert.equal((await command('reset')).result.ok, true);
    assert.equal((await store.read(guest.profileId)).cable, undefined);
}
